import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
import { promises as fs } from 'node:fs'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1576, height: 980 } })
  await page.route('**/studio', (route) => route.fulfill({ contentType: 'application/json', headers: { 'access-control-allow-origin': '*' }, body: JSON.stringify({ roots: [], activities: [] }) }))
  await page.route('**/assistant/alerts', (route) => route.fulfill({ contentType: 'application/json', headers: { 'access-control-allow-origin': '*' }, body: '{"notifications":[]}' }))
  await page.goto('http://127.0.0.1:5173')
  await page.getByRole('button', { name: /INICIAR JARVIS/ }).waitFor()
  await page.evaluate(async () => {
    const { useStore } = await import('/src/store.ts')
    useStore.setState({ phase: 'listening', connected: ['jarvis', 'jarvis_projects', 'jarvis_word', 'jarvis_assistant'], level: .22 })
  })
  await fs.mkdir('.ui-check.local', { recursive: true })
  await page.getByRole('button', { name: /01 Assistente/ }).click()
  await page.getByRole('button', { name: 'Mostrar painéis', exact: true }).waitFor()
  assert.equal(await page.locator('.mission-left').isVisible(), false)
  assert.equal(await page.locator('.mission-right').isVisible(), false)
  await page.getByRole('button', { name: 'Mostrar painéis', exact: true }).click()
  await page.getByText('Todos os sistemas,', { exact: false }).waitFor()
  await page.getByText('HORÁRIO DE BRASÍLIA', { exact: true }).waitFor()
  await page.waitForTimeout(500)
  await page.reload()
  await page.getByRole('button', { name: 'Ocultar painéis', exact: true }).waitFor()
  assert.equal(await page.locator('.mission-left').isVisible(), true)
  await page.getByRole('button', { name: 'Ocultar painéis', exact: true }).click()
  await page.getByRole('button', { name: 'Mostrar painéis', exact: true }).waitFor()
  assert.equal(await page.locator('.mission-left').isVisible(), false)
  await page.screenshot({ path: '.ui-check.local/mode-assistant.png' })
  await page.getByRole('button', { name: /02 Professor/ }).click()
  await page.getByRole('main', { name: 'Área do Professor' }).waitFor()
  await page.getByLabel('Anotações da aula').fill('Revisar o laço for e praticar com listas.')
  await page.screenshot({ path: '.ui-check.local/mode-professor.png' })
  await page.getByRole('button', { name: /03 Desenvolvedor/ }).click()
  await page.getByRole('main', { name: 'Área do Desenvolvedor' }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Aplicar no projeto', exact: true }).isDisabled(), true)
  await page.getByLabel('Rascunho de código').fill('def saudacao(nome):\n    return f"Olá, {nome}!"\n\nprint(saudacao("Mundo"))')
  assert.equal(await page.getByRole('button', { name: 'Explicar código', exact: true }).isEnabled(), true)
  await page.screenshot({ path: '.ui-check.local/mode-developer.png' })
  await page.waitForTimeout(500)
  await page.reload()
  await page.getByRole('main', { name: 'Área do Desenvolvedor' }).waitFor()
  assert.match(await page.getByLabel('Rascunho de código').inputValue(), /def saudacao/)
  await page.getByRole('button', { name: /02 Professor/ }).click()
  assert.match(await page.getByLabel('Anotações da aula').inputValue(), /Revisar o laço/)
  await page.getByRole('button', { name: 'Escolher material ↗', exact: true }).click()
  await page.getByRole('heading', { name: 'Aula com PDF e exemplos na tela', exact: true }).waitFor()
  await page.getByLabel('Fechar ajustes', { exact: true }).click()
  for (const [width, height] of [[1280, 720], [390, 844]]) {
    await page.setViewportSize({ width, height })
    for (const [index, name] of [['01', 'Assistente'], ['02', 'Professor'], ['03', 'Desenvolvedor']]) {
      await page.getByRole('button', { name: new RegExp(`${index} ${name}`) }).click()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
      await page.screenshot({ path: `.ui-check.local/mode-${name.toLowerCase()}-${width}.png` })
    }
  }
  console.log('Três modos, rascunho e anotações persistentes, atalhos e layout em 1576/1280/390 px passaram.')
} finally { await browser.close() }

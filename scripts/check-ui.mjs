import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { fakeMicrophoneArgs, installSpeechMock, powerOn, speak } from './voice-test-helpers.mjs'

const browser = await chromium.launch({ channel: 'chrome', headless: true, args: fakeMicrophoneArgs })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  await installSpeechMock(page)
  await page.goto('http://localhost:5173', { waitUntil: 'domcontentloaded' })
  // Native speech is deterministic in this UI test. Neural audio is tested separately.
  await page.evaluate(async () => (await import('/src/workspace.ts')).useWorkspace.getState().setSettings({ naturalVoice: false }))
  await powerOn(page)
  assert.equal(await page.locator('.voice-console, .voice-text-form').count(), 0)
  assert.equal(await page.getByRole('textbox', { name: 'Digite seu pedido' }).count(), 0)
  assert.equal(await page.locator('.scene-light').count(), 1)
  assert.equal(await page.locator('.holo-core-canvas, .neural-sphere-canvas').count(), 1)
  assert.equal(await page.locator('.scene canvas, .hands-canvas').count(), 1)
  assert.equal(await page.evaluate(() => window.__testRecognition.lang), 'pt-BR')
  assert.equal(await page.evaluate(() => window.__testRecognition.maxAlternatives), 3)
  const settings = await page.evaluate(async () => (await import('/src/workspace.ts')).useWorkspace.getState().settings)
  assert.equal(settings.voiceVolume, 1)
  assert.equal(settings.fast, true)
  assert.equal(settings.speechPause, 0.8)
  assert.equal(settings.visualTheme, 'sphere')
  await page.evaluate(async () => (await import('/src/workspace.ts')).useWorkspace.getState().setSettings({ visualTheme: 'reactor' }))
  await page.locator('.holo-ticks, .holo-particles').first().waitFor({ state: 'attached' })
  assert.equal(await page.locator('.holo-core-canvas, .neural-sphere-canvas').count(), 0)
  await page.evaluate(async () => (await import('/src/workspace.ts')).useWorkspace.getState().setSettings({ visualTheme: 'sphere' }))
  await page.locator('.holo-core-canvas, .neural-sphere-canvas').waitFor()
  await page.evaluate(async () => {
    (await import('/src/workspace.ts')).useWorkspace.getState().setSettings({ visualTheme: 'helios', helios: { introOnStartup: false, quality: 'eco' } })
    const store = (await import('/src/store.ts')).useStore.getState()
    store.setPhase('listening')
    store.setLevel(.65)
  })
  const helios = page.frameLocator('iframe[title="Holograma do reator HELIOS"]')
  await helios.getByRole('heading', { name: 'REATOR HELIOS', includeHidden: true }).waitFor({ state: 'attached' })
  await page.waitForFunction(() => {
    const frame = document.querySelector('iframe[title="Holograma do reator HELIOS"]')
    return frame?.contentDocument?.querySelector('#status')?.textContent === 'ESCUTANDO'
  })
  assert.equal(await helios.locator('.mic-control').evaluate((element) => getComputedStyle(element).display), 'none')
  assert.equal(await helios.locator('#introOverlay').evaluate((element) => element.classList.contains('show')), false)
  assert.equal(await helios.locator('#quality').inputValue(), 'eco')
  await helios.locator('#panel summary').click()
  await helios.locator('#speed').evaluate((element) => { element.value = '2'; element.dispatchEvent(new Event('input', { bubbles: true })); element.dispatchEvent(new Event('change', { bubbles: true })) })
  await helios.locator('[data-palette="cyan"]').click()
  await helios.locator('#pause').click()
  await page.waitForFunction(async () => {
    const helios = (await import('/src/workspace.ts')).useWorkspace.getState().settings.helios
    return helios.speed === 2 && helios.color === 'cyan' && helios.paused
  })
  await page.evaluate(async () => (await import('/src/workspace.ts')).flushWorkspace())
  const savedHelios = await page.evaluate(() => JSON.parse(localStorage.getItem('jarvis.workspace.v1')).settings.helios)
  assert.equal(savedHelios.color, 'cyan')
  assert.equal(savedHelios.paused, true)
  assert.equal(await page.locator('.holo-core-canvas, .neural-sphere-canvas, .scene canvas').count(), 0)
  await page.evaluate(async () => (await import('/src/workspace.ts')).useWorkspace.getState().setSettings({ visualTheme: 'sphere' }))
  await page.locator('.holo-core-canvas, .neural-sphere-canvas').waitFor()
  const safeLinks = await page.evaluate(async () => {
    const { sanitisePanelHtml } = await import('/src/ui/sanitise.ts')
    return sanitisePanelHtml('<a href="https://example.com/source">Fonte</a><a href="javascript:alert(1)">inválido</a>')
  })
  assert.match(safeLinks, /href="https:\/\/example\.com\/source"/)
  assert.match(safeLinks, /rel="noopener noreferrer"/)
  assert.doesNotMatch(safeLinks, /javascript:/)
  const safeArticle = await page.evaluate(async () => {
    const { sanitisePanelHtml } = await import('/src/ui/sanitise.ts')
    return sanitisePanelHtml('<h2>Introdução</h2><p>Texto do artigo.</p><hr><h3>Fontes</h3>')
  })
  assert.match(safeArticle, /<h2>Introdução<\/h2>/)
  assert.match(safeArticle, /<h3>Fontes<\/h3>/)
  assert.match(safeArticle, /<hr>/)
  await speak(page, ['Responda apenas:', 'teste de voz concluído.'])
  await page.locator('.log-user').filter({ hasText: 'Responda apenas: teste de voz concluído.' }).waitFor()
  await page.locator('.log-jarvis').filter({ hasText: /teste de voz concluído/i }).waitFor({ timeout: 45000 })
  await page.waitForFunction(async () => (await import('/src/store.ts')).useStore.getState().phase === 'listening', undefined, { timeout: 15000 })
  await page.clock.install()
  await page.clock.fastForward(16000)
  assert.equal(await page.evaluate(async () => (await import('/src/store.ts')).useStore.getState().phase), 'listening')
  await mkdir('.ui-check.local', { recursive: true })
  await page.screenshot({ path: '.ui-check.local/desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '.ui-check.local/mobile.png' })
  await page.keyboard.press('Escape')
  assert.equal(await page.evaluate(async () => (await import('/src/store.ts')).useStore.getState().phase), 'dormant')
  await page.keyboard.press('Space')
  assert.equal(await page.evaluate(async () => (await import('/src/store.ts')).useStore.getState().phase), 'listening')
  console.log('PASS: painel removido, entrada pt-BR, resposta Gemini por fala simulada, escuta contínua, pausa e reativação.')
} finally { await browser.close() }

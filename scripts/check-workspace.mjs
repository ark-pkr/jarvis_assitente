import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
import { fakeMicrophoneArgs, installSpeechMock, powerOn, speak } from './voice-test-helpers.mjs'

const browser = await chromium.launch({ channel: 'chrome', headless: true, args: fakeMicrophoneArgs })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  await installSpeechMock(page)
  const ready = async () => {
    await powerOn(page)
  }
  await page.goto('http://localhost:5173'); await ready()
  await page.getByRole('button', { name: 'Histórico e ajustes', exact: true }).click()
  await page.getByRole('button', { name: 'Memória', exact: true }).click()
  await page.getByRole('textbox', { name: 'Preferências e memória' }).fill('Meu código de teste é LARANJA-42. Prefiro respostas curtas.')
  await page.getByRole('button', { name: 'Salvar memória', exact: true }).click()
  await page.getByText('Preferências salvas.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Áudio', exact: true }).click()
  await page.getByRole('slider', { name: 'Volume da música' }).press('Home')
  await page.getByRole('button', { name: 'Fechar ajustes', exact: true }).click()
  await speak(page, 'Qual é meu código de teste? Responda apenas o código.')
  await page.locator('.log-jarvis').filter({ hasText: /LARANJA-42/ }).waitFor({ timeout: 45000 })
  await page.keyboard.press('Escape')
  await page.evaluate(async () => (await import('/src/workspace.ts')).flushWorkspace())
  await page.reload(); await ready()
  await page.locator('.log-jarvis').filter({ hasText: /LARANJA-42/ }).waitFor()
  assert.equal(await page.evaluate(async () => (await import('/src/workspace.ts')).useWorkspace.getState().settings.music), 0)
  await page.getByRole('button', { name: 'Histórico e ajustes', exact: true }).click()
  await page.getByRole('textbox', { name: 'Buscar no histórico' }).fill('código de teste')
  assert.equal(await page.locator('.session-list > div').count(), 1)
  const previousId = await page.evaluate(async () => (await import('/src/workspace.ts')).useWorkspace.getState().active)
  await page.getByRole('button', { name: 'Nova conversa', exact: true }).click()
  assert.equal(await page.evaluate(async () => (await import('/src/store.ts')).useStore.getState().turns.length), 0)
  await page.getByRole('textbox', { name: 'Buscar no histórico' }).fill('código de teste')
  await page.locator('.session-list > div > button:first-child').click()
  assert.equal(await page.evaluate(async () => (await import('/src/workspace.ts')).useWorkspace.getState().active), previousId)
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar histórico', exact: true }).click()
  const download = await downloadEvent
  assert.equal(download.suggestedFilename(), 'jarvis-historico.json')
  await page.screenshot({ path: '.ui-check.local/history.png' })
  await page.getByRole('button', { name: 'Memória', exact: true }).click()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Apagar histórico e memória', exact: true }).click()
  assert.equal(await page.getByRole('textbox', { name: 'Preferências e memória' }).inputValue(), '')
  assert.equal(await page.evaluate(async () => (await import('/src/workspace.ts')).useWorkspace.getState().sessions.length), 1)
  await page.getByRole('button', { name: 'Fechar ajustes', exact: true }).click()
  await speak(page, 'Lembre-se para futuras conversas: meu projeto de teste se chama AURORA. Salve isso na memória usando a ferramenta.')
  await page.getByRole('dialog', { name: 'Confirmar ação do JARVIS' }).waitFor({ timeout: 45000 })
  await page.screenshot({ path: '.ui-check.local/approval.png' })
  await page.waitForTimeout(1300)
  await page.getByRole('button', { name: 'Autorizar esta ação', exact: true }).press('Enter')
  await page.waitForFunction(async () => (await import('/src/workspace.ts')).useWorkspace.getState().memory.includes('AURORA'), undefined, { timeout: 15000 })
  await page.keyboard.press('Escape')
  console.log('PASS: memória real no Gemini, histórico após recarregar, busca, troca de conversa, exportação, exclusão e confirmação por ferramenta.')
} finally { await browser.close() }

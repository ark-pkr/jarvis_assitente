import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const ready = async () => {
    await page.getByRole('button', { name: /INICIAR JARVIS/ }).waitFor()
    await page.evaluate(async () => (await import('/src/store.ts')).useStore.setState({ phase: 'dormant' }))
  }
  await page.goto('http://localhost:5173'); await ready()
  await page.getByRole('button', { name: 'Histórico e ajustes', exact: true }).click()
  await page.getByRole('button', { name: 'Aprender', exact: true }).click()
  await page.getByLabel('Modo de ajuda', { exact: true }).selectOption('tutor')
  await page.getByLabel('Nível dos estudos', { exact: true }).selectOption('Intermediário')
  await page.getByLabel('Objetivo de aprendizagem', { exact: true }).fill('Criar um sistema de estoque')
  await page.getByRole('checkbox', { name: 'Concluir Lógica de programação', exact: true }).check()
  await page.evaluate(async () => (await import('/src/workspace.ts')).flushWorkspace())
  await page.reload(); await ready()
  await page.getByRole('button', { name: 'Histórico e ajustes', exact: true }).click()
  await page.getByRole('button', { name: 'Aprender', exact: true }).click()
  assert.equal(await page.getByLabel('Modo de ajuda', { exact: true }).inputValue(), 'tutor')
  assert.equal(await page.getByRole('checkbox', { name: 'Concluir Lógica de programação', exact: true }).isChecked(), true)
  assert.equal(await page.getByLabel('Objetivo de aprendizagem', { exact: true }).inputValue(), 'Criar um sistema de estoque')
  const context = await page.evaluate(async () => (await import('/src/workspace.ts')).conversationContext())
  assert.match(context.memory, /Atue como professor/)
  assert.match(context.memory, /Intermediário/)
  await mkdir('.ui-check.local', { recursive: true })
  await page.screenshot({ path: '.ui-check.local/learning.png' })
  await page.getByRole('button', { name: 'Praticar', exact: true }).click()
  await page.locator('.log-jarvis').filter({ hasText: /\S/ }).waitFor({ timeout: 45000 })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Histórico e ajustes', exact: true }).click()
  await page.getByRole('button', { name: 'Arquivos', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: 'Autorizar e conhecer pasta', exact: true }).isDisabled(), true)
  assert.equal(await page.getByRole('button', { name: 'Prévia por tipo', exact: true }).isDisabled(), true)
  assert.equal(await page.getByRole('button', { name: 'Criar projeto completo', exact: true }).isDisabled(), true)
  assert.equal(await page.getByRole('button', { name: 'Compartilhar diagnósticos do VS Code', exact: true }).isEnabled(), true)
  await page.getByRole('textbox', { name: 'Pasta do projeto', exact: true }).fill('C:\\exemplo\\pasta-de-teste')
  assert.equal(await page.getByRole('button', { name: 'Autorizar e conhecer pasta', exact: true }).isEnabled(), true)
  await page.getByRole('textbox', { name: 'Tarefa com arquivos', exact: true }).fill('Crie uma API de demonstração')
  assert.equal(await page.getByRole('button', { name: 'Criar projeto completo', exact: true }).isEnabled(), true)
  assert.equal(await page.getByRole('button', { name: 'Compartilhar diagnósticos do VS Code', exact: true }).isEnabled(), true)
  await page.screenshot({ path: '.ui-check.local/files.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Aprender', exact: true }).click()
  await page.screenshot({ path: '.ui-check.local/learning-mobile.png' })
  const panel = await page.locator('.workspace-panel').boundingBox()
  assert.ok(panel.x >= 0 && panel.x + panel.width <= 390)
  console.log('PASS: modos, progresso e objetivo persistem; tutor responde via Gemini; arquivos exigem pasta; layout móvel válido.')
} finally { await browser.close() }
